// Leitura/gravação de js/plugins.js e leitura (com cache) dos arquivos de plugin.

import { parsePlugin, defaultsOf } from "./parser.js";
import { t } from "../i18n.js";

export const PLUGINS_JS = "js/plugins.js";
export const PLUGINS_DIR = "js/plugins";

const infoCache = new Map();   // nome -> Promise<info>

// Interpreta o texto de js/plugins.js e devolve a lista $plugins.
export function parsePluginsJs(text) {
    const src = String(text || "");
    const at = src.indexOf("$plugins");
    const start = src.indexOf("[", at >= 0 ? at : 0);
    const end = src.lastIndexOf("]");
    if (start < 0 || end < start) {
        return [];
    }
    const body = src.slice(start, end + 1);
    try {
        return JSON.parse(body);
    } catch {
        try {
            // Arquivo editado à mão com sintaxe JS (vírgula sobrando, aspas simples...).
            return new Function("return " + body)() || [];
        } catch (e) {
            throw new Error(t("Invalid %1: %2", null, "js/plugins.js", e.message));
        }
    }
}

// Gera o texto de js/plugins.js exatamente no formato do RPG Maker MZ:
// cabeçalho de 2 linhas, `var $plugins =`, `[`, um plugin por linha (JSON compacto,
// separados por vírgula), `];` e quebra de linha final (LF).
export function serializePluginsJs(list) {
    const lines = list.map(p => JSON.stringify({
        name: String(p.name),
        status: !!p.status,
        description: String(p.description || ""),
        parameters: p.parameters || {}
    }));
    return "// Generated by RPG Maker.\n" +
        "// Do not edit this file directly.\n" +
        "var $plugins =\n" +
        "[\n" +
        (lines.length ? lines.join(",\n") + "\n" : "") +
        "];\n";
}

export async function loadPluginList() {
    const res = await fetch("/api/file?path=" + encodeURIComponent(PLUGINS_JS), { cache: "no-store" });
    if (res.status === 404) {
        return [];
    }
    if (!res.ok) {
        throw new Error(t("Failed to read %1: %2", null, "js/plugins.js", res.status));
    }
    return parsePluginsJs(await res.text());
}

export async function savePluginList(list) {
    const text = serializePluginsJs(list);
    const res = await fetch("/api/file?path=" + encodeURIComponent(PLUGINS_JS), {
        method: "PUT",
        headers: { "Content-Type": "text/javascript; charset=utf-8" },
        body: text
    });
    if (!res.ok) {
        throw new Error(t("Failed to write %1: %2", null, "js/plugins.js", res.status));
    }
    return text;
}

// Nomes (sem .js) dos arquivos em js/plugins, em ordem alfabética.
export async function listPluginFiles(api) {
    let entries = [];
    try {
        entries = api && api.project ? await api.project.list(PLUGINS_DIR)
            : await (await fetch("/api/list?dir=" + encodeURIComponent(PLUGINS_DIR))).json();
    } catch {
        entries = [];
    }
    return entries
        .filter(e => !e.dir && /\.js$/i.test(e.name))
        .map(e => e.name.replace(/\.js$/i, ""))
        .sort((a, b) => a.localeCompare(b, undefined, { sensitivity: "base" }));
}

async function fetchPluginText(name) {
    const res = await fetch("/project/js/plugins/" + encodeURIComponent(name) + ".js", { cache: "no-store" });
    if (!res.ok) {
        return null;
    }
    return res.text();
}

// Informações do cabeçalho do plugin (cache por nome; `fresh` relê o arquivo).
export function getPluginInfo(name, { fresh = false } = {}) {
    if (!fresh && infoCache.has(name)) {
        return infoCache.get(name);
    }
    const p = fetchPluginText(name).then(text => {
        if (text == null) {
            const info = parsePlugin("", name);
            info.missing = true;
            return info;
        }
        const info = parsePlugin(text, name);
        info.missing = false;
        return info;
    });
    infoCache.set(name, p);
    p.catch(() => infoCache.delete(name));
    return p;
}

export function clearInfoCache(name) {
    if (name) {
        infoCache.delete(name);
    } else {
        infoCache.clear();
    }
}

// Parâmetros na ordem de declaração: mantém os valores existentes dos parâmetros
// ainda declarados e usa @default para os novos (comportamento do "Atualizar" do MZ).
export function mergeParameters(info, oldParams) {
    const out = defaultsOf(info.params);
    for (const k of Object.keys(out)) {
        if (oldParams && Object.prototype.hasOwnProperty.call(oldParams, k)) {
            out[k] = String(oldParams[k]);
        }
    }
    return out;
}

// Entrada nova de $plugins a partir do arquivo.
export function newEntry(info) {
    return {
        name: info.name,
        status: true,
        description: info.plugindesc || "",
        parameters: defaultsOf(info.params)
    };
}
